/**
 * Obtiene todas las imágenes disponibles para un producto.
 * Si el producto tiene galería configurada, la devuelve (asegurando la principal primero).
 * Si no, devuelve un arreglo con solo la imagen principal (o vacío si no tiene).
 */
export function getProductImages(slug: string, primaryImage?: string | null): string[] {
  const gallery = PRODUCT_GALLERIES[slug];
  if (gallery && gallery.length > 0) {
    if (primaryImage && !gallery.includes(primaryImage)) {
      return [primaryImage, ...gallery];
    }
    return gallery;
  }
  return primaryImage ? [primaryImage] : [];
}

/**
 * Devuelve la imagen secundaria (si existe) para efectos de hover en cards de catálogo.
 */
export function getSecondaryImage(slug: string): string | null {
  const gallery = PRODUCT_GALLERIES[slug];
  if (gallery && gallery.length > 1) {
    return gallery[1];
  }
  return null;
}
